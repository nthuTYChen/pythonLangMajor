# Create a string object and store it in the variable str
# In object-oriented programming (OOP), data is represented as objects.
# A string is an object, and it contains data (the characters), properties
# (the number of characters, for instance), and methods (functions that can
# operate on that data).
str = "Is this just a string?"

# Call the lower() method of the string object.
# The dot (.) is used to access a method or attribute belonging to an object.
# lower() converts all alphabetic characters in the string to lowercase.
print(str.lower())

# Create an integer object with the value 1000 and store it in the variable num.
# Like strings, integers are also objects in Python.
num = 1000

# Call the bit_length() method of the integer object.
# bit_length() returns the number of bits needed to represent the integer
# in binary, excluding the sign and leading zeros.
print(num.bit_length())