# Basic operations: addition, subtraction, multiplication, and division
print(1 + 2)
print(1 - 2)
print(1 * 2)
print(1 / 2)

# More math operators
print(1 // 2) # Division, but the result is rounded to the floor
print(2 ** 4) # 2 to the power of 4
print(10 % 3) # Division, but the result is the remainder

# Complex operations: Subtraction and mutiplication are computed first as in real life
print(2 * 4 / 2)
print(2 - 1 / 5)
print(2 * 4 % 3)
print(2 * 4 ** 2)

# Operations with strings
print("Different " + "words " + "are " + "put " + "together.") # Addition
print("Repeat this!" * 3) # Repetition
